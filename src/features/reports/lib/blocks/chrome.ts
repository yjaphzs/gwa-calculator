import { displayHost, escapeHtml } from "@/features/reports/lib/format";

// The app's calculator mark (Lucide "calculator") in amber on a dark tile —
// inline SVG so the print never waits on an image request.
const LOGO_SVG = `
<svg viewBox="0 0 32 32" aria-hidden="true">
  <rect width="32" height="32" rx="7" fill="#27272a" />
  <g transform="translate(4 4)" fill="none" style="stroke: var(--report-mark)" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
    <rect width="16" height="20" x="4" y="2" rx="2" />
    <line x1="8" x2="16" y1="6" y2="6" />
    <line x1="16" x2="16" y1="14" y2="18" />
    <path d="M16 10h.01M12 10h.01M8 10h.01M12 14h.01M8 14h.01M12 18h.01M8 18h.01" />
  </g>
</svg>`;

interface HeaderOptions {
  appName: string;
  title: string;
  subtitle: string;
}

/** Dark header band with the brand, the document title, and the "Personal copy" mark. */
export function renderHeader({ appName, title, subtitle }: HeaderOptions): string {
  return `
<header>
  <div class="band">
    <div class="band-top">
      <div class="brand">${LOGO_SVG}<span>${escapeHtml(appName)}</span></div>
      <span class="chip">Personal copy</span>
    </div>
    <h1 class="doc-title">${escapeHtml(title)}</h1>
    <p class="doc-subtitle">${escapeHtml(subtitle)}</p>
  </div>
  <div class="stripe"></div>
</header>`;
}

/** Repeats at the foot of every printed page. */
export function renderRunningFooter(appName: string, appUrl: string): string {
  return `
<footer class="running-footer">
  <span><strong>${escapeHtml(appName)}</strong>${escapeHtml(displayHost(appUrl))}</span>
  <span>Personal reference copy, not an official record</span>
</footer>`;
}

/**
 * Wording must stay consistent with Terms §2/§5 and Privacy §9
 * (src/app/(legal)/…) — update those pages if this changes.
 */
export function renderDisclaimer(appName: string, generatedOn: string): string {
  return `
<p class="disclaimer">
  Generated by ${escapeHtml(appName)} on ${escapeHtml(generatedOn)} from data entered
  by the user. This document is for personal reference only. It is
  <strong>not</strong> an official academic record and is not issued,
  certified, or endorsed by any school, registrar, or other authority.
</p>`;
}
